APP_DIR = Path(__file__).parent
SQLITE_PATH = APP_DIR / "complaints.db"

DATABASE_URL = None
try:
    DATABASE_URL = st.secrets.get("database", {}).get("url", None)
except Exception:
    pass

DATABASE_URL = DATABASE_URL or os.getenv("DATABASE_URL")

st.set_page_config(
    page_title="CivicSense AI",
    page_icon="🏙️",
    layout="wide"
)

CATEGORIES = [
    "Road / Pothole",
    "Garbage / Sanitation",
    "Water Leakage",
    "Drainage / Sewage",
    "Streetlight",
    "Other"
]

STATUSES = [
    "Submitted",
    "Under Review",
    "In Progress",
    "Resolved"
]

PRIORITIES = ["Critical", "High", "Medium", "Low"]

if DATABASE_URL:
    if DATABASE_URL.startswith("postgres://"):
        DATABASE_URL = DATABASE_URL.replace(
            "postgres://", "postgresql://", 1
        )
    engine = create_engine(DATABASE_URL, pool_pre_ping=True)
    DB_KIND = "PostgreSQL"
else:
    engine = create_engine(
        f"sqlite:///{SQLITE_PATH}",
        connect_args={"check_same_thread": False}
    )
    DB_KIND = "local SQLite"


def init_db():
    with engine.begin() as conn:
        if DB_KIND == "PostgreSQL":
            conn.execute(text("""
                CREATE TABLE IF NOT EXISTS complaints (
                    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                    name TEXT NOT NULL,
                    category TEXT NOT NULL,
                    description TEXT NOT NULL,
                    location TEXT NOT NULL,
                    severity TEXT NOT NULL,
                    score INTEGER NOT NULL,
                    priority TEXT NOT NULL,
                    reason TEXT NOT NULL,
                    duplicate_of INTEGER,
                    status TEXT NOT NULL DEFAULT 'Submitted',
                    created_at TEXT NOT NULL
                )
            """))
        else:
            conn.execute(text("""
                CREATE TABLE IF NOT EXISTS complaints (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    category TEXT NOT NULL,
                    description TEXT NOT NULL,
                    location TEXT NOT NULL,
                    severity TEXT NOT NULL,
                    score INTEGER NOT NULL,
                    priority TEXT NOT NULL,
                    reason TEXT NOT NULL,
                    duplicate_of INTEGER,
                    status TEXT NOT NULL DEFAULT 'Submitted',
                    created_at TEXT NOT NULL
                )
            """))


def get_complaints():
    with engine.connect() as conn:
        rows = conn.execute(text("""
            SELECT * FROM complaints
            ORDER BY created_at DESC, id DESC
        """)).mappings().all()

    return [dict(row) for row in rows]


def insert_complaint(values):
    columns = """
        (name, category, description, location, severity,
         score, priority, reason, duplicate_of, status, created_at)
    """
    params = {key: value for key, value in values.items()}

    with engine.begin() as conn:
        if DB_KIND == "PostgreSQL":
            result = conn.execute(text(f"""
                INSERT INTO complaints {columns}
                VALUES (
                    :name, :category, :description, :location,
                    :severity, :score, :priority, :reason,
                    :duplicate_of, 'Submitted', :created_at
                )
                RETURNING id
            """), params)

            return int(result.scalar_one())

        result = conn.execute(text(f"""
            INSERT INTO complaints {columns}
            VALUES (
                :name, :category, :description, :location,
                :severity, :score, :priority, :reason,
                :duplicate_of, 'Submitted', :created_at
            )
        """), params)

        return int(result.lastrowid)


def update_status(complaint_id, new_status):
    with engine.begin() as conn:
        conn.execute(
            text("""
                UPDATE complaints
                SET status = :status
                WHERE id = :id
            """),
            {"status": new_status, "id": complaint_id}
        )


def score_complaint(category, description, severity, location):
    text_content = (description + " " + category).lower()

    score = {
        "Low": 15,
        "Medium": 35,
        "High": 55,
        "Critical": 70
    }[severity]

    reasons = [f"User-reported severity: {severity.lower()}"]

    rules = [
        (
            (
                "accident", "injury", "injured", "dangerous",
                "life threatening", "open manhole",
                "electric wire", "electrocution"
            ),
            25,
            "possible immediate safety risk"
        ),
        (
            (
                "flood", "flooding", "burst pipe", "major leak",
                "sewage overflow", "overflowing sewage"
            ),
            18,
            "possible infrastructure or sanitation hazard"
        ),
        (
            (
                "school", "hospital", "bus stop",
                "main road", "highway", "market"
            ),
            8,
            "location may affect many people"
        ),
        (
            ("small", "minor", "slight"),
            -8,
            "description indicates a potentially minor issue"
        )
    ]

    for keywords, points, reason in rules:
        if any(word in text_content for word in keywords):
            score += points
            reasons.append(reason)

    score = max(0, min(100, score))

    if score >= 80:
        priority = "Critical"
    elif score >= 60:
        priority = "High"
    elif score >= 35:
        priority = "Medium"
    else:
        priority = "Low"

    if not location.strip():
        reasons.append("location missing; follow-up needed")

    return score, priority, "; ".join(reasons).capitalize() + "."


def find_duplicate(description, category, location, rows):
    if not rows:
        return None, 0.0

    texts = [
        f"{row['category']} {row['description']} {row['location']}"
        for row in rows
    ]

    new_text = f"{category} {description} {location}"

    try:
        matrix = TfidfVectorizer(
            stop_words="english",
            ngram_range=(1, 2)
        ).fit_transform(texts + [new_text])

        similarities = cosine_similarity(
            matrix[-1], matrix[:-1]
        ).flatten()

    except ValueError:
        return None, 0.0

    best_index = int(similarities.argmax())
    best_score = float(similarities[best_index])

    if best_score >= 0.42:
        return rows[best_index], best_score

    return None, best_score


def get_admin_credentials():
    try:
        username = st.secrets["admin"]["username"]
        password = st.secrets["admin"]["password"]

        if username and password:
            return str(username), str(password)

    except Exception:
        pass

    return None, None


def admin_login():
    expected_user, expected_password = get_admin_credentials()

    if not expected_user or not expected_password:
        st.error(
            "Admin access is not configured yet. Add [admin] "
            "username and password in Streamlit app Secrets, "
            "then reload."
        )

        st.code(
            '[admin]\n'
            'username = "your_admin_username"\n'
            'password = "use-a-long-unique-password"',
            language="toml"
        )
        return False

    if st.session_state.get("admin_authenticated", False):
        return True

    st.subheader("🔐 Admin login")

    with st.form("admin_login_form"):
        username = st.text_input("Admin username")
        password = st.text_input("Admin password", type="password")

        submitted = st.form_submit_button(
            "Log in",
            type="primary"
        )

    if submitted:
        valid_user = hmac.compare_digest(username, expected_user)
        valid_password = hmac.compare_digest(
            password, expected_password
        )

        if valid_user and valid_password:
            st.session_state["admin_authenticated"] = True
            st.rerun()
        else:
            st.error("Incorrect username or password.")

    return False


